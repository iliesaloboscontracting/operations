// Release check: the throwaway test copy - safety refusals, the test .env, the snapshot copy, row counts, the schema
// push, throwaway logins and site links. Everything here writes ONLY to <app>/prisma/test.db, <app>/.env (one we
// wrote ourselves) and the run's own temp folder.
import { copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { createHash, randomBytes, scryptSync } from "node:crypto";
import path from "node:path";
import { run } from "./util.mjs";

export const ENV_MARKER = "# release-check test env - generated by scripts/release-check, deleted at the end. Not a real .env.";

// Settings a test copy must never have: phone alerts, Xero, Microsoft Graph, AI services and server-to-server keys.
// They are stripped from the server's own environment as well as never written to the test .env.
export const FORBIDDEN_ENV = /^(VAPID_|XERO_|GRAPH_|ANTHROPIC_|OPENAI_|ACTUALS_SECRET$|DATABASE_URL$|AUTH_SECRET$|DOC_SEARCH_SOURCE$|DOC_SEARCH_LOCAL_ROOT$|DOC_SEARCH_TEST_APPROVE$|SITE_BASE_URL$|ESTIMATING_URL$|SEARCH_INDEX_PATH$|NODE_OPTIONS$)/;

export function paths(appDir, runTmp) {
  const prismaDir = path.join(appDir, "prisma");
  const testDb = path.join(prismaDir, "test.db");
  return {
    appDir, prismaDir, testDb, envFile: path.join(appDir, ".env"),
    dbUrl: "file:" + testDb.split(path.sep).join("/"),
    files: path.join(runTmp, "files"), searchIndex: path.join(runTmp, "search-index", "search.db"),
    defaultSearchIndex: path.resolve(appDir, "..", "operations-search", "search.db"),
    netLog: path.join(runTmp, "outbound.jsonl"), serverLog: path.join(runTmp, "server.log"),
  };
}

// Refuse anything that could touch a real install. Returns a list of reasons (empty = safe to go on).
export function refusals(p, { snapshot, port }) {
  const r = [];
  const pkg = existsSync(path.join(p.appDir, "package.json")) ? JSON.parse(readFileSync(path.join(p.appDir, "package.json"), "utf8")) : null;
  if (!pkg || pkg.name !== "operations") r.push(`${p.appDir} is not an Operations checkout (package.json name).`);
  if (!existsSync(path.join(p.appDir, "node_modules"))) r.push(`${p.appDir} has no node_modules - run \`npm ci\` there first.`);
  if (/^\/srv\//.test(p.appDir.replace(/\\/g, "/"))) r.push("Refusing to run under /srv - that is the production server's layout.");
  if (Number(port) === 3000) r.push("Port 3000 is the live app's port - use another (default 3001).");
  if (existsSync(p.envFile) && !readFileSync(p.envFile, "utf8").includes(ENV_MARKER))
    r.push(`${p.envFile} exists and wasn't written by the release check - run in a separate worktree (never the shared folder or a server).`);
  for (const f of [".env.local", ".env.production", ".env.production.local"])
    if (existsSync(path.join(p.appDir, f))) r.push(`${f} exists in ${p.appDir} - Next would load it on top of the test settings.`);
  if (!snapshot) r.push("--snapshot <path to a SQLite copy> is required.");
  else if (!existsSync(snapshot)) r.push(`Snapshot not found: ${snapshot}`);
  else if (path.resolve(snapshot).toLowerCase() === p.testDb.toLowerCase()) r.push("The snapshot can't be the test database itself.");
  else if (/[\\/]prisma[\\/]dev\.db$/i.test(path.resolve(snapshot)) && path.resolve(snapshot).toLowerCase().startsWith(p.appDir.toLowerCase()))
    r.push("Refusing to use this checkout's own prisma/dev.db as the snapshot - pass a copy.");
  return r;
}

export function writeEnv(p, port) {
  for (const d of ["tool-photos", "invoice-files", "receipt-files", "compliance-files"]) mkdirSync(path.join(p.files, d), { recursive: true });
  const f = (d) => JSON.stringify(path.join(p.files, d).split(path.sep).join("/"));
  const lines = [
    ENV_MARKER,
    `DATABASE_URL=${JSON.stringify(p.dbUrl)}`,
    // A fresh random secret per run: sessions and QR codes only need to agree within this test server.
    `AUTH_SECRET=${randomBytes(48).toString("base64url")}`,
    `SITE_BASE_URL="http://127.0.0.1:${port}"`,
    `TOOL_PHOTO_DIR=${f("tool-photos")}`, `INVOICE_FILE_DIR=${f("invoice-files")}`,
    `RECEIPT_FILE_DIR=${f("receipt-files")}`, `COMPLIANCE_FILE_DIR=${f("compliance-files")}`,
    "RECEIPT_READING=off", "DAILY_LOG_REMINDER=off",
    // Never the real Estimating app: port 9 refuses every connection.
    `ESTIMATING_URL="http://127.0.0.1:9"`,
    `SEARCH_INDEX_PATH=${JSON.stringify(p.searchIndex.split(path.sep).join("/"))}`,
    // Deliberately absent: VAPID_*, XERO_*, GRAPH_*, ANTHROPIC_API_KEY, OPENAI_API_KEY, ACTUALS_SECRET.
  ];
  writeFileSync(p.envFile, lines.join("\n") + "\n");
  return Object.fromEntries(lines.slice(1).filter((l) => !l.startsWith("#")).map((l) => { const i = l.indexOf("="); return [l.slice(0, i), l.slice(i + 1).replace(/^"|"$/g, "")]; }));
}

// The environment every child process gets: this shell's, minus anything a test copy must never carry, plus ours.
export function childEnv(testEnv, extra = {}) {
  const e = {};
  for (const [k, v] of Object.entries(process.env)) if (!FORBIDDEN_ENV.test(k)) e[k] = v;
  return { ...e, ...testEnv, NEXT_TELEMETRY_DISABLED: "1", ...extra };
}

export function copySnapshot(p, snapshot) {
  for (const f of [p.testDb, p.testDb + "-journal", p.testDb + "-wal", p.testDb + "-shm"]) rmSync(f, { force: true });
  copyFileSync(snapshot, p.testDb);
}

// Row counts per table (node:sqlite, read-only - works before the Prisma client is generated).
export function rowCounts(file) {
  const { DatabaseSync } = process.getBuiltinModule("node:sqlite");
  const db = new DatabaseSync(file, { readOnly: true });
  try {
    const tables = db.prepare("select name from sqlite_master where type='table' and name not like 'sqlite_%' and name not like '_prisma%' order by name").all();
    const out = {};
    for (const { name } of tables) out[name] = Number(db.prepare(`select count(*) as n from "${name.replace(/"/g, '""')}"`).get().n);
    return out;
  } finally { db.close(); }
}

export function compareCounts(before, after) {
  const dropped = Object.keys(before).filter((t) => !(t in after));
  const added = Object.keys(after).filter((t) => !(t in before));
  const changed = Object.keys(before).filter((t) => t in after && before[t] !== after[t]).map((t) => `${t}: ${before[t]} -> ${after[t]}`);
  return { dropped, added, changed };
}

// `prisma db push` on the test copy. A data-loss warning stops it unless acceptDataLoss - and the warning is returned.
export async function dbPush(p, env, acceptDataLoss) {
  const prismaCli = path.join(p.appDir, "node_modules", "prisma", "build", "index.js");
  const args = [prismaCli, "db", "push", "--schema", path.join(p.prismaDir, "schema.prisma")];
  const first = await run(process.execPath, args, { cwd: p.appDir, env, timeoutMs: 300_000 });
  const lossLines = (s) => s.split(/\r?\n/).filter((l) => /data loss|will be lost|cannot be executed|unique constraint|dropped|--accept-data-loss/i.test(l)).map((l) => l.trim()).filter(Boolean);
  if (first.code === 0) return { ok: true, warnings: lossLines(first.out), out: first.out, accepted: false };
  const warnings = lossLines(first.out);
  if (!warnings.length) return { ok: false, warnings: [], out: first.out, error: "prisma db push failed" };
  if (!acceptDataLoss) return { ok: false, warnings, out: first.out, error: "prisma db push reports possible DATA LOSS - stopped (pass --accept-data-loss only with the release owner's approval)" };
  const second = await run(process.execPath, [...args, "--accept-data-loss"], { cwd: p.appDir, env, timeoutMs: 300_000 });
  return { ok: second.code === 0, warnings, out: second.out, accepted: true, error: second.code === 0 ? undefined : "prisma db push --accept-data-loss failed" };
}

export function prismaFor(p) {
  if (!p.dbUrl.endsWith("/prisma/test.db")) throw new Error("not the test db: " + p.dbUrl);
  const req = createRequire(path.join(p.appDir, "package.json"));
  const { PrismaClient } = req("@prisma/client");
  return new PrismaClient({ datasources: { db: { url: p.dbUrl } } });
}

// Throwaway logins, one per role. Passwords are random and held in memory only - never written to a file.
export const TEST_ROLES = {
  MANAGER: { role: "MANAGER" },
  MANAGER_DIRECTOR: { role: "MANAGER", directorAccess: true },
  ADMIN: { role: "ADMIN", directorAccess: true },
  ADMIN_PLAIN: { role: "ADMIN" },
  VIEWER: { role: "VIEWER" },
  TIMESHEETS: { role: "TIMESHEETS" },
  ACCOUNTS: { role: "ACCOUNTS" },
  DIRECTOR: { role: "DIRECTOR" },
};
export async function makeUsers(db) {
  const tag = randomBytes(4).toString("hex");
  const users = {};
  for (const [key, spec] of Object.entries(TEST_ROLES)) {
    const email = `rc-${key.toLowerCase().replace(/_/g, "-")}-${tag}@release-check.test`;
    const password = randomBytes(18).toString("base64url");
    const salt = randomBytes(16);
    const passwordHash = `scrypt$${salt.toString("hex")}$${scryptSync(password, salt, 64).toString("hex")}`;
    const u = await db.user.create({ data: { email, name: `Release check ${key}`, passwordHash, role: spec.role, directorAccess: !!spec.directorAccess } });
    users[key] = { id: u.id, email, password, role: spec.role };
  }
  return users;
}

// Two logins are known by their EMAIL, not their role: the owner (src/lib/owner.ts OWNER_EMAIL) and the Operations AI
// (src/lib/session.ts BUILDING_AGENT_EMAIL). On the TEST COPY only, their password hash is replaced with a random
// in-memory one (or the login is created if the copy has none), so owner-only and AI-only rules can be exercised.
export async function makeSpecialUsers(db, appDir) {
  const read = (rel, re) => { try { return readFileSync(path.join(appDir, rel), "utf8").match(re)?.[1] ?? null; } catch { return null; } };
  const specs = [
    { key: "OWNER", email: read("src/lib/owner.ts", /OWNER_EMAIL\s*=\s*"([^"]+)"/), role: "ADMIN", name: "Release check owner" },
    { key: "OPS_AI", email: read("src/lib/session.ts", /BUILDING_AGENT_EMAIL\s*=\s*"([^"]+)"/), role: "MANAGER", name: "Release check Operations AI" },
  ];
  const out = {}, notes = [];
  for (const s of specs) {
    if (!s.email) { notes.push(`${s.key}: email constant not found in the candidate`); continue; }
    const password = randomBytes(18).toString("base64url");
    const salt = randomBytes(16);
    const passwordHash = `scrypt$${salt.toString("hex")}$${scryptSync(password, salt, 64).toString("hex")}`;
    const existing = await db.user.findUnique({ where: { email: s.email } });
    const u = existing
      ? await db.user.update({ where: { id: existing.id }, data: { passwordHash, active: true } })
      : await db.user.create({ data: { email: s.email, name: s.name, passwordHash, role: s.role } });
    out[s.key] = { id: u.id, email: s.email, password, role: u.role };
    notes.push(`${s.key}: ${existing ? `existing ${u.role} login, password replaced on the copy` : `created as ${s.role} on the copy`}`);
  }
  return { users: out, notes };
}

const newSecret = () => randomBytes(24).toString("base64url");
export async function makeLink(db, kind, resourceId, extra = {}) {
  const secret = newSecret();
  const l = await db.siteLink.create({ data: { kind, resourceId, tokenHash: createHash("sha256").update(secret).digest("hex"), createdBy: "release-check", ...extra } });
  return { id: l.id, secret };
}

// A SUPERVISOR link (the most recently used supervisor's person) and an OFFICE link (a person's own office link).
export async function makeLinks(db) {
  const sup = await db.siteLink.findFirst({ where: { kind: "SUPERVISOR", revokedAt: null, resource: { active: true } }, orderBy: { lastUsedAt: "desc" } });
  const office = await db.siteLink.findFirst({ where: { kind: "OFFICE", revokedAt: null, resourceId: { not: null } } });
  const out = { missing: [] };
  if (sup) out.sup = { ...(await makeLink(db, "SUPERVISOR", sup.resourceId)), resourceId: sup.resourceId }; else out.missing.push("no active SUPERVISOR link in the snapshot");
  if (office) out.office = { ...(await makeLink(db, "OFFICE", office.resourceId)), resourceId: office.resourceId }; else out.missing.push("no personal OFFICE link in the snapshot");
  return out;
}
